"""Aggregate fidelity/reports/<run>/cases/*.json into results.csv and report.md.

    .venv/bin/python -m fidelity.report [--dir fidelity/reports/phase2]
"""

from __future__ import annotations

import argparse
import csv
import json
import statistics
from pathlib import Path

from fidelity.cases import BACKEND


def g(d, *path, default=None):
    for p in path:
        if not isinstance(d, dict) or p not in d:
            return default
        d = d[p]
    return d


def f(v, nd=3):
    if v is None:
        return "-"
    if isinstance(v, float):
        return f"{v:.{nd}f}"
    return str(v)


def rows(cases: list[dict]) -> list[dict]:
    out = []
    for c in cases:
        for mode, m in (c.get("modes") or {}).items():
            if m.get("status") != "ok":
                out.append({"case": c["case"], "kind": c["kind"], "mode": mode, "status": m.get("status"),
                            "error": m.get("error") or m.get("reason")})
                continue
            vol = next((m[k] for k in m if k.startswith("volume_vs")), {})
            vref = next((k[len("volume_vs_"):] for k in m if k.startswith("volume_vs")), None)
            deg = m.get("degradation") or {}
            out.append({
                "case": c["case"], "kind": c["kind"], "mode": mode, "status": "ok", "pieces": m["pieces"],
                "orientation": m.get("orientation"), "reference_2d": c.get("reference_2d"),
                "side_iou": g(m, "side_vs_reference", "raw", "iou"),
                "side_bf": g(m, "side_vs_reference", "raw", "bf"),
                "side_hausdorff_mm": g(m, "side_vs_reference", "raw", "hausdorff_mm"),
                "side_hd95_mm": g(m, "side_vs_reference", "raw", "hd95_mm"),
                "side_env6_iou": g(m, "side_vs_reference", "envelope6mm", "iou"),
                "side_env6_bf": g(m, "side_vs_reference", "envelope6mm", "bf"),
                "side_iou_vs_generator_input": g(m, "side_vs_generator_input", "raw", "iou"),
                "torso_recall": g(m, "region_recall_vs_reference", "torso"),
                "head_recall": g(m, "region_recall_vs_reference", "head"),
                "limb_recall": g(m, "region_recall_vs_reference", "limb"),
                "volume_reference": vref,
                "volume_iou": vol.get("volume_iou"), "front_iou_3d": vol.get("proj_iou_front"),
                "top_iou_3d": vol.get("proj_iou_top"), "chamfer_mm": vol.get("chamfer_mm"),
                "coverage_6mm": vol.get("coverage_6mm"), "material_outside_ref": vol.get("material_outside_ref"),
                "body25d_vs_ref_volume_iou": g(vol, "generator_body_vs_reference", "volume_iou"),
                "body25d_vs_ref_front_iou": g(vol, "generator_body_vs_reference", "proj_iou_front"),
                "kit_vs_body25d_coverage_6mm": g(vol, "kit_vs_generator_body", "coverage_6mm"),
                "intended_front_iou_3d": g(vol, "intended", "proj_iou_front"),
                "intended_coverage_6mm": g(vol, "intended", "coverage_6mm"),
                "ribs_requested": deg.get("ribs_requested"), "ribs_placed": deg.get("ribs_placed"),
                "vertebrae_requested": deg.get("vertebrae_requested"), "vertebrae_placed": deg.get("vertebrae_placed"),
                "rib_failed_attempts": deg.get("rib_failed_attempts"), "vertebra_shrunk": deg.get("vertebra_shrunk"),
                "dropped_plates": ",".join(deg.get("dropped_plates") or []),
                "trimmed_axis_fraction": deg.get("trimmed_axis_fraction"),
                "side_iou_intended": deg.get("side_iou_intended"),
                "front_area_actual_mm2": deg.get("front_area_actual_mm2"),
                "front_area_intended_mm2": deg.get("front_area_intended_mm2"),
                "sheet_fit_attempts": m.get("sheet_fit_attempts"),
                "note": m.get("note", ""),
            })
    return out


def stat(values):
    v = [x for x in values if isinstance(x, (int, float))]
    if not v:
        return "-"
    return f"{statistics.median(v):.3f} [{min(v):.3f}-{max(v):.3f}] n={len(v)}"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dir", default=str(BACKEND / "fidelity" / "reports" / "phase2"))
    args = ap.parse_args()
    d = Path(args.dir)
    cases = [json.loads(p.read_text()) for p in sorted((d / "cases").glob("*.json"))]
    order = {"fixture": 0, "gtmesh": 1, "photo": 2}
    cases.sort(key=lambda c: (order.get(c["kind"], 9), c["case"]))
    (d / "results.json").write_text(json.dumps(cases, indent=1))
    R = rows(cases)
    keys = sorted({k for r in R for k in r}, key=lambda k: list(R[0].keys()).index(k) if k in R[0] else 999)
    with open(d / "results.csv", "w", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=keys)
        w.writeheader()
        for r in R:
            w.writerow(r)

    L = ["# Phase 2 fidelity measurement (generated by fidelity/report.py)", ""]
    L += ["Settings = web-app defaults: 3 mm plywood, kerf 0.15, clearance 0.10, 250 mm, 30 pieces target, "
          "advanced, 600x400 sheet, kit frame on. Side view = reference camera. Voxel pitch 1 mm. "
          "BF tolerance = 2 % of size (5 mm). Envelope = closing radius 6 mm.", ""]
    L += ["## Stage chain (2D, vs reference)", "",
          "| case | ref | seg method | seg IoU | largest IoU | normalized IoU | normalized BF | normalized HD mm | trace==prod |",
          "|---|---|---|---|---|---|---|---|---|"]
    for c in cases:
        st = c.get("stages_2d_vs_reference") or {}
        L.append(f"| {c['case']} | {'GT' if (c.get('reference_2d') or '').startswith('ground-truth') else 'seg (no GT)'} | "
                 f"{g(c, 'segmentation', 'method')} | {f(g(st, 'segmentation_all_components', 'iou'))} | "
                 f"{f(g(st, 'largest_component', 'iou'))} | {f(g(st, 'normalized_final', 'iou'))} | "
                 f"{f(g(st, 'normalized_final', 'bf'))} | {f(g(st, 'normalized_final', 'hausdorff_mm'), 1)} | "
                 f"{c.get('normalization_trace_equals_production')} |")
    L += ["", "## Reconstruction / 3D stages", "",
          "| case | AI 3D | align IoU | depth ratio | gate | recon vs GT vol IoU | 2.5D body vs recon vol IoU | "
          "est. body vs GT vol IoU | est. body vs GT front IoU | upload remesh vs GT vol IoU | upload 2.5D vs GT vol IoU | upload 2.5D vs GT front IoU |",
          "|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for c in cases:
        r = c.get("reconstruction") or {}
        L.append(f"| {c['case']} | {r.get('source', 'n/a')} | {f(r.get('alignment_iou'))} | {f(r.get('depth_ratio'))} | "
                 f"{r.get('gate', '-')} | {f(g(r, 'reconstruction_vs_gt', 'volume_iou'))} | "
                 f"{f(g(r, 'stage_2p5d_body_vs_reconstruction', 'volume_iou'))} | "
                 f"{f(g(c, 'stage_3d_estimated_body_vs_gt', 'volume_iou'))} | "
                 f"{f(g(c, 'stage_3d_estimated_body_vs_gt', 'proj_iou_front'))} | "
                 f"{f(g(c, 'upload_remesh_vs_gt', 'volume_iou'))} | {f(g(c, 'upload_2p5d_body_vs_gt', 'volume_iou'))} | "
                 f"{f(g(c, 'upload_2p5d_body_vs_gt', 'proj_iou_front'))} |")
    L += ["", "## Per case and mode (final assembled kit)", "",
          "| case | mode | pieces | orient. | side IoU | side BF | side HD mm | env6 IoU | torso rec. | head rec. | limb rec. | "
          "3D ref | vol IoU | front IoU | top IoU | chamfer mm | cover@6mm |",
          "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for r in R:
        if r["status"] != "ok":
            L.append(f"| {r['case']} | {r['mode']} | {r['status']}: {r.get('error')} |" + " |" * 14)
            continue
        L.append(f"| {r['case']} | {r['mode']} | {r['pieces']} | {r['orientation']} | {f(r['side_iou'])} | {f(r['side_bf'])} | "
                 f"{f(r['side_hausdorff_mm'], 1)} | {f(r['side_env6_iou'])} | {f(r['torso_recall'], 2)} | {f(r['head_recall'], 2)} | "
                 f"{f(r['limb_recall'], 2)} | {r['volume_reference'] or '-'} | {f(r['volume_iou'])} | {f(r['front_iou_3d'])} | "
                 f"{f(r['top_iou_3d'])} | {f(r['chamfer_mm'], 1)} | {f(r['coverage_6mm'])} |")
    L += ["", "## Constraint-driven degradation (fossil kit)", "",
          "| case | mode | ribs req/placed | rib failed attempts | vert req/placed | vert shrunk | dropped plates | axis trimmed | "
          "side IoU actual -> intended | front area actual -> intended mm2 | front IoU 3D actual -> intended | sheet-fit attempts |",
          "|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for r in R:
        if r["status"] != "ok" or r.get("ribs_requested") is None:
            continue
        L.append(f"| {r['case']} | {r['mode']} | {r['ribs_requested']}/{r['ribs_placed']} | {r['rib_failed_attempts']} | "
                 f"{r['vertebrae_requested']}/{r['vertebrae_placed']} | {r['vertebra_shrunk']} | {r['dropped_plates'] or '-'} | "
                 f"{f(r['trimmed_axis_fraction'], 3)} | {f(r['side_iou'])} -> {f(r['side_iou_intended'])} | "
                 f"{f(r['front_area_actual_mm2'], 0)} -> {f(r['front_area_intended_mm2'], 0)} | "
                 f"{f(r['front_iou_3d'])} -> {f(r['intended_front_iou_3d'])} | {r['sheet_fit_attempts']} |")
    L += ["", "## Baselines (median [min-max] n)", "", "| mode | kind | side IoU | side BF | env6 IoU | torso recall | vol IoU | front IoU 3D | chamfer mm | cover@6mm |",
          "|---|---|---|---|---|---|---|---|---|---|"]
    ok = [r for r in R if r["status"] == "ok"]
    for mode in sorted({r["mode"] for r in ok}):
        for kind in ("fixture", "gtmesh", "photo"):
            sel = [r for r in ok if r["mode"] == mode and r["kind"] == kind]
            if not sel:
                continue
            L.append(f"| {mode} | {kind} | {stat(r['side_iou'] for r in sel)} | {stat(r['side_bf'] for r in sel)} | "
                     f"{stat(r['side_env6_iou'] for r in sel)} | {stat(r['torso_recall'] for r in sel)} | "
                     f"{stat(r['volume_iou'] for r in sel)} | {stat(r['front_iou_3d'] for r in sel)} | "
                     f"{stat(r['chamfer_mm'] for r in sel)} | {stat(r['coverage_6mm'] for r in sel)} |")
    (d / "report.md").write_text("\n".join(L) + "\n")
    print(f"{len(cases)} cases, {len(R)} case-modes -> {d}")


if __name__ == "__main__":
    main()
